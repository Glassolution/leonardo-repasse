import { urlImagem } from './imagens'

export type Categoria = 'Hatch' | 'Sedã' | 'SUV' | 'Picape'
export type Status = 'disponivel' | 'reservado' | 'vendido'

export type Veiculo = {
  /** Usado na URL: /veiculo/<id>. Sem espaços nem acentos. */
  id: string
  marca: string
  modelo: string
  versao: string
  categoria: Categoria
  anoFabricacao: number
  anoModelo: number
  km: number
  motor: string
  cambio: 'Manual' | 'Automático' | 'CVT'
  combustivel: 'Flex' | 'Gasolina' | 'Diesel' | 'Híbrido'
  cor: string
  /** Sem preço, o site mostra "Consultar valor". */
  preco?: number
  /** Preço antigo, aparece riscado quando o valor baixa. */
  precoAnterior?: number
  /** Valor da tabela FIPE do mês, para mostrar a diferença do repasse. */
  fipe?: number
  /** Itens de série/opcionais em destaque no card. */
  itens: string[]
  /** URLs ou caminhos dentro de /public. Ex.: '/veiculos/hrv-exl-2023/1.jpg' */
  fotos: string[]
  status: Status
  observacoes?: string
  /** Data de entrada no estoque (AAAA-MM-DD), usada para ordenar. */
  entrada: string
}

